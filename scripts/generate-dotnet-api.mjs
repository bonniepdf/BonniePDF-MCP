import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dll = resolve(
  process.argv.find(a => a.endsWith('.dll')) ??
    resolve(root, '../BonniePDF-NET/BonniePDF/bin/Release/net10.0/BonniePDF.dll')
);
const result = spawnSync('dotnet', ['run', '--project', resolve(root, 'scripts/dotnet-api'), '--', dll], {
  encoding: 'utf8',
  windowsHide: true,
  maxBuffer: 8_000_000,
});
if (result.status !== 0) throw new Error(result.stderr || result.stdout);
const data = JSON.parse(result.stdout.slice(result.stdout.indexOf('{')));
const source =
  '// Generated by scripts/generate-dotnet-api.mjs from the public BonniePDF .NET API.\nexport const DOTNET_API: Record<string, { enums: string[] | null; properties: Record<string, { type: string; writable: boolean }> }> = ' +
  JSON.stringify(data) +
  ';\n';
const target = resolve(root, 'src/dotnet-api.ts');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== source) throw new Error('Native export API metadata is stale');
} else await writeFile(target, source);
